"""Mã lỗi trả về dạng { "error": { "code", "message" } } (docs/api.md)."""
from enum import Enum


class ErrorCode(str, Enum):
    # File chung
    FILE_REQUIRED = "FILE_REQUIRED"
    FILE_TOO_LARGE = "FILE_TOO_LARGE"
    TOO_MANY_FILES = "TOO_MANY_FILES"
    FILE_TYPE_NOT_ALLOWED = "FILE_TYPE_NOT_ALLOWED"  # chỉ nhận PDF, ảnh, video, âm thanh
    # Đăng nhập, phân quyền
    INVALID_CREDENTIALS = "INVALID_CREDENTIALS"
    UNAUTHENTICATED = "UNAUTHENTICATED"
    FORBIDDEN = "FORBIDDEN"
    NOT_CASE_PARTICIPANT = "NOT_CASE_PARTICIPANT"
    # Lưu chứng
    RECORD_NOT_FOUND = "RECORD_NOT_FOUND"
    RECEIPT_NOT_FOUND = "RECEIPT_NOT_FOUND"
    # Vụ án
    CASE_NOT_FOUND = "CASE_NOT_FOUND"
    CASE_EXISTS = "CASE_EXISTS"
    PARTICIPANT_NOT_FOUND = "PARTICIPANT_NOT_FOUND"
    INVALID_PARTICIPANT_ROLE = "INVALID_PARTICIPANT_ROLE"
    INVALID_STATE = "INVALID_STATE"
    USER_NOT_FOUND = "USER_NOT_FOUND"
    PARTICIPANT_EXISTS = "PARTICIPANT_EXISTS"
    # Lô, chứng cứ
    FILE_CODE_NOT_FOUND = "FILE_CODE_NOT_FOUND"
    META_MISMATCH = "META_MISMATCH"
    CASE_CLOSED = "CASE_CLOSED"
    LOT_NOT_FOUND = "LOT_NOT_FOUND"
    EVIDENCE_NOT_FOUND = "EVIDENCE_NOT_FOUND"
    # Giám định
    FILE_CHANGED_SINCE_RECEIPT = "FILE_CHANGED_SINCE_RECEIPT"
    # Hồ sơ chốt
    APPEAL_REQUIRED = "APPEAL_REQUIRED"
    DOSSIER_NOT_FOUND = "DOSSIER_NOT_FOUND"
    # Kiểm tra tệp, quản trị
    INVALID_RECEIPT_FORMAT = "INVALID_RECEIPT_FORMAT"
    USERNAME_EXISTS = "USERNAME_EXISTS"
    EMAIL_EXISTS = "EMAIL_EXISTS"
    # Blockchain
    CHAIN_UNAVAILABLE = "CHAIN_UNAVAILABLE"  # RPC lỗi (dùng cho POST /verify)
    INVALID_OTS = "INVALID_OTS"  # file .ots hỏng, sai hash file, hoặc máy chủ lịch ngoài danh sách cho phép
    OTS_EXISTS = "OTS_EXISTS"  # file đã có dấu OpenTimestamps
    CALENDAR_UNAVAILABLE = "CALENDAR_UNAVAILABLE"  # máy chủ lịch OpenTimestamps không trả lời
    # Chung
    VALIDATION_ERROR = "VALIDATION_ERROR"
    INTERNAL_ERROR = "INTERNAL_ERROR"
